import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'qa');
const base = 'http://127.0.0.1:8766';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const blocked = [];
await context.route('**/*', route => {
  if (['GET', 'HEAD'].includes(route.request().method())) return route.continue();
  blocked.push({ method: route.request().method(), url: route.request().url() });
  return route.abort();
});
const page = await context.newPage();
const errors = [];
const failures = [];
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.url().startsWith(base) && response.status() >= 400) failures.push({ url: response.url(), status: response.status() }); });
try {
  await page.goto(base + '/simulateur', { waitUntil: 'networkidle' });
  await page.locator('#sel-marque').selectOption('TOYOTA');
  const option = await page.locator('#sel-modele option').evaluateAll(options => options.find(option => option.textContent.trim().toUpperCase() === 'COROLLA')?.value);
  assert(option, 'Modèle COROLLA disponible dans le sélecteur existant.');
  await page.locator('#sel-modele').selectOption(option);
  await page.locator('#inp-annee').fill('2010');
  await page.locator('#sel-type').selectOption('tourisme');
  await page.locator('#sel-origine').selectOption('usa');
  await page.locator('#chk-tgc').uncheck();
  // Contexte local éphémère de QA : aucune coordonnée ni aucun paiement transmis.
  await page.evaluate(() => { leadMem = true; paidOK = () => true; calculate(); applyLeadGate(); });
  await page.locator('#paid-declarations-content').getByText(/9 observations/).waitFor();
  await page.locator('#paid-declarations').scrollIntoViewIfNeeded();
  assert(await page.locator('#paid-declarations').isVisible());
  const panel = await page.locator('#paid-declarations-content').innerText();
  const flat = panel.replace(/[\s\u00a0\u202f]/g, '');
  assert(panel.includes('exercice 2026'));
  assert(panel.includes('catégorie B'));
  assert(flat.includes('2610518FCFA'), 'CAF médiane 2 610 518 F.');
  assert(flat.includes('923472FCFA'), 'Droits médians 923 472 F.');
  const fees = await page.evaluate(async () => {
    const amount = id => Number(document.getElementById(id).textContent.replace(/[^0-9]/g, ''));
    const markup = buildDevisHTML('QA', 'Locale', '', '');
    const emailDoc = new DOMParser().parseFromString(markup, 'text/html');
    const emailRows = Array.from(emailDoc.querySelectorAll('tr')).map(row => row.textContent);
    await loadJsPDF();
    const pdf = new window.jspdf.jsPDF({ unit: 'mm', format: 'a4' });
    const pdfText = [];
    const originalText = pdf.text.bind(pdf);
    pdf.text = function (text, ...args) { pdfText.push(Array.isArray(text) ? text.join(' ') : String(text)); return originalText(text, ...args); };
    buildPdfReport(pdf, collectReportData());
    return { bfu: amount('res-bfu'), prestation: amount('res-prestation'), fees: amount('res-user-frais'), duties: amount('res-total-douane'), total: amount('res-total'), emailRows, pdfText };
  });
  assert.equal(fees.bfu, 100000);
  assert.equal(fees.prestation, 100000);
  assert.equal(fees.fees, 551815);
  assert.equal(fees.total, fees.duties + fees.fees);
  for (const label of ['Provision BFU / GUCE / PAC', 'Prestation AD TRANS LOGISTICS']) {
    const row = fees.emailRows.find(text => text.includes(label));
    assert(row && row.replace(/\s/g, '').includes('100000XOF'), 'Montant HTML cohérent : ' + label);
    const index = fees.pdfText.findIndex(text => text.includes(label));
    assert(index >= 0 && fees.pdfText[index + 1].replace(/\s/g, '').includes('100000XOF'), 'Montant PDF cohérent : ' + label);
  }
  await page.locator('#sel-valuation-source').selectOption('manual');
  assert(await page.locator('#transaction-box').isVisible(), 'Saisie manuelle ouverte pour un véhicule 2010.');
  await page.locator('#sel-transaction-currency').selectOption('XOF');
  await page.locator('#sel-transaction-basis').selectOption('caf');
  await page.locator('#inp-transaction-value').fill('10000000');
  const manual = await page.evaluate(() => ({ caf: Number(document.querySelector('#res-cif').textContent.replace(/[^0-9]/g, '')), page: document.querySelector('#trace-page').textContent, source: getSimulationData().input_data.base_transactionnelle }));
  assert.equal(manual.caf, 10000000);
  assert.equal(manual.source, 'caf');
  assert(manual.page.includes('aucune cote Argus utilisée'));
  await page.locator('#inp-transaction-value').fill('');
  assert.equal(await page.locator('#res-content').isVisible(), false, 'Une valeur manuelle vide invalide le résultat précédent.');
  await page.locator('#inp-transaction-value').fill('10000000');
  await page.locator('#argus-catalogue > summary').click();
  await page.waitForFunction(() => !document.querySelector('#argus-catalogue-query').disabled);
  await page.locator('#argus-catalogue-query').fill('Audi S3 Berline');
  await page.locator('#argus-catalogue-year').selectOption('2016');
  await page.locator('.argus-catalogue-row').filter({ hasText: /15\s?600/ }).first().locator('button').click();
  assert.equal(await page.locator('#sel-valuation-source').inputValue(), 'reference', 'Sélection Argus : retour automatique au mode référence.');
  const audiCaf = await page.locator('#res-cif').textContent();
  assert.equal(Number(audiCaf.replace(/[^0-9]/g, '')), 10832976);
  await page.locator('#sel-marque').selectOption('TOYOTA');
  await page.locator('#sel-modele').selectOption(option);
  await page.locator('#inp-annee').fill('2010');
  await page.locator('#sel-type').selectOption('tourisme');
  await page.locator('#chk-tgc').uncheck();
  await page.locator('#paid-declarations-content').getByText(/9 observations/).waitFor();
  await fs.mkdir(out, { recursive: true });
  await page.locator('#paid-declarations').screenshot({ path: path.join(out, 'declarations-corolla-2010.png') });
  await page.locator('#inp-annee').fill('2027');
  await page.waitForFunction(() => document.querySelector('#paid-declarations-content').textContent.trim() === '');
  assert.equal(await page.locator('#paid-declarations').isVisible(), false);
  const staleAfterYearChange = await page.locator('#paid-declarations-content').textContent();
  assert.equal(staleAfterYearChange, '');
  await page.locator('#inp-annee').fill('2010');
  await page.locator('#paid-declarations-content').getByText(/9 observations/).waitFor();
  await page.locator('#sel-marque').selectOption('BMW');
  assert.equal(await page.locator('#paid-declarations-content').textContent(), '');
  assert.equal(await page.locator('#paid-declarations').isVisible(), false);
  const headings = await page.locator('h1, .sim-hero .tag, .tag').allTextContents();
  assert(!headings.some(text => /barème réel|barème officiel/i.test(text)));
  assert.equal(errors.length, 0, errors.join('\n'));
  const applicationFailures = failures.filter(failure => !failure.url.endsWith('/_vercel/insights/script.js'));
  assert.equal(applicationFailures.length, 0, JSON.stringify(applicationFailures));
  const report = { ok: true, panel, manual, provisions: { bfu: fees.bfu, prestation: fees.prestation, fees: fees.fees, duties: fees.duties, total: fees.total }, checks: ['COROLLA 2010 catégorie B : 9 observations 2026', 'CAF médiane 2610518', 'droits médians 923472', 'panneau visible', 'BFU/prestation 100000 chacun écran + HTML + PDF', 'total cohérent, autres frais inchangés', 'CAF/AVD manuelle sur 2010 remplace la référence sans double fret', 'saisie manuelle vide invalide le calcul', 'sélection Audi rétablit automatiquement la source référence', 'changement année vide le panneau', 'reset marque vide le panneau', 'en-têtes sans barème réel/officiel', 'GET/HEAD uniquement'], errors, applicationFailures, localAnalyticsUnavailable: failures.filter(failure => failure.url.endsWith('/_vercel/insights/script.js')), blockedMethods: blocked.map(request => request.method) };
  await fs.writeFile(path.join(out, 'declarations-corolla-2010.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally {
  await browser.close();
}
